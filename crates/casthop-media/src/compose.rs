//! CPU compositor: scale tiles into a 1280×720 (or custom) RGBA buffer
//! and stamp a lower-third. Nearest (filter=0) or bilinear (filter=1).

const BG: u32 = 0x0b0b0dff;
const ACCENT: u32 = 0x6d64f7ff;
const BAR: u32 = 0x121316e6;
const TEXT: u32 = 0xf3f4f6ff;
const MUTED: u32 = 0x9aa0abff;

pub struct Compositor {
    pub width: u32,
    pub height: u32,
    pub pixels: Vec<u8>,
    pub tile: Vec<u8>,
}

impl Compositor {
    pub fn new(width: u32, height: u32) -> Self {
        let n = (width as usize) * (height as usize) * 4;
        Self {
            width,
            height,
            pixels: vec![0; n],
            tile: Vec::new(),
        }
    }

    pub fn reserve_tile(&mut self, bytes: usize) {
        if self.tile.len() < bytes {
            self.tile.resize(bytes, 0);
        }
    }

    pub fn clear(&mut self, rgba: u32) {
        let c = if rgba == 0 { BG } else { rgba };
        let r = ((c >> 24) & 0xff) as u8;
        let g = ((c >> 16) & 0xff) as u8;
        let b = ((c >> 8) & 0xff) as u8;
        let a = (c & 0xff) as u8;
        for px in self.pixels.chunks_exact_mut(4) {
            px[0] = r;
            px[1] = g;
            px[2] = b;
            px[3] = a;
        }
    }

    pub fn blit(&mut self, src_w: u32, src_h: u32, dx: u32, dy: u32, dw: u32, dh: u32, bilinear: bool) {
        if src_w == 0 || src_h == 0 || dw == 0 || dh == 0 {
            return;
        }
        let src_stride = (src_w as usize) * 4;
        let need = src_stride * src_h as usize;
        if self.tile.len() < need {
            return;
        }
        if bilinear {
            self.blit_bilinear(need, src_w, src_h, dx, dy, dw, dh);
        } else {
            self.blit_nearest(need, src_w, src_h, dx, dy, dw, dh);
        }
    }

    fn blit_nearest(&mut self, _src_len: usize, src_w: u32, src_h: u32, dx: u32, dy: u32, dw: u32, dh: u32) {
        let dst_w = self.width;
        let dst_h = self.height;
        for y in 0..dh {
            let sy = (y as u64 * src_h as u64 / dh as u64) as u32;
            let dy = dy + y;
            if dy >= dst_h {
                break;
            }
            let src_row = (sy as usize) * (src_w as usize) * 4;
            let dst_row = (dy as usize) * (dst_w as usize) * 4;
            for x in 0..dw {
                let sx = (x as u64 * src_w as u64 / dw as u64) as u32;
                let dx = dx + x;
                if dx >= dst_w {
                    break;
                }
                let si = src_row + (sx as usize) * 4;
                let di = dst_row + (dx as usize) * 4;
                self.pixels[di..di + 4].copy_from_slice(&self.tile[si..si + 4]);
            }
        }
    }

    fn blit_bilinear(&mut self, src_len: usize, src_w: u32, src_h: u32, dx: u32, dy: u32, dw: u32, dh: u32) {
        let dst_w = self.width;
        let dst_h = self.height;
        let max_x = src_w.saturating_sub(1);
        let max_y = src_h.saturating_sub(1);
        for y in 0..dh {
            let fy = (y as f32 + 0.5) * (src_h as f32 / dh as f32) - 0.5;
            let y0 = fy.floor().max(0.0) as u32;
            let y1 = (y0 + 1).min(max_y);
            let ty = fy - y0 as f32;
            let dy = dy + y;
            if dy >= dst_h {
                break;
            }
            for x in 0..dw {
                let fx = (x as f32 + 0.5) * (src_w as f32 / dw as f32) - 0.5;
                let x0 = fx.floor().max(0.0) as u32;
                let x1 = (x0 + 1).min(max_x);
                let tx = fx - x0 as f32;
                let dx = dx + x;
                if dx >= dst_w {
                    break;
                }
                let c00 = sample(&self.tile[..src_len], src_w, x0, y0);
                let c10 = sample(&self.tile[..src_len], src_w, x1, y0);
                let c01 = sample(&self.tile[..src_len], src_w, x0, y1);
                let c11 = sample(&self.tile[..src_len], src_w, x1, y1);
                let mut out = [0u8; 4];
                for k in 0..4 {
                    let a = c00[k] as f32 + (c10[k] as f32 - c00[k] as f32) * tx;
                    let b = c01[k] as f32 + (c11[k] as f32 - c01[k] as f32) * tx;
                    out[k] = (a + (b - a) * ty).round() as u8;
                }
                let di = (dy as usize * dst_w as usize + dx as usize) * 4;
                self.pixels[di..di + 4].copy_from_slice(&out);
            }
        }
    }

    pub fn banner(&mut self, title: &str, subtitle: &str) {
        let h = (self.height as f32 * 0.11).round().max(56.0) as u32;
        let y0 = self.height.saturating_sub(h + (self.height / 28));
        let x0 = self.width / 24;
        let w = self.width - x0 * 2;
        fill_rect(&mut self.pixels, self.width, self.height, x0, y0, w, h, BAR);
        fill_rect(
            &mut self.pixels,
            self.width,
            self.height,
            x0,
            y0,
            (w as f32 * 0.012).max(4.0) as u32,
            h,
            ACCENT,
        );
        let text_x = x0 + 18;
        let title_y = y0 + h / 2 - 10;
        draw_text(
            &mut self.pixels,
            self.width,
            self.height,
            text_x,
            title_y,
            title,
            2,
            TEXT,
        );
        if !subtitle.is_empty() {
            draw_text(
                &mut self.pixels,
                self.width,
                self.height,
                text_x + (title.len() as u32 * 14) + 16,
                title_y + 2,
                subtitle,
                1,
                MUTED,
            );
        }
    }
}

fn sample(src: &[u8], src_w: u32, x: u32, y: u32) -> [u8; 4] {
    let i = (y as usize * src_w as usize + x as usize) * 4;
    [src[i], src[i + 1], src[i + 2], src[i + 3]]
}

fn fill_rect(dst: &mut [u8], dw: u32, dh: u32, x: u32, y: u32, w: u32, h: u32, rgba: u32) {
    let sr = ((rgba >> 24) & 0xff) as u16;
    let sg = ((rgba >> 16) & 0xff) as u16;
    let sb = ((rgba >> 8) & 0xff) as u16;
    let sa = (rgba & 0xff) as u16;
    if sa == 0 {
        return;
    }
    for row in 0..h {
        let yy = y + row;
        if yy >= dh {
            break;
        }
        for col in 0..w {
            let xx = x + col;
            if xx >= dw {
                break;
            }
            let i = (yy as usize * dw as usize + xx as usize) * 4;
            if sa == 255 {
                dst[i] = sr as u8;
                dst[i + 1] = sg as u8;
                dst[i + 2] = sb as u8;
                dst[i + 3] = 255;
            } else {
                let inv = 255 - sa;
                dst[i] = ((dst[i] as u16 * inv + sr * sa) / 255) as u8;
                dst[i + 1] = ((dst[i + 1] as u16 * inv + sg * sa) / 255) as u8;
                dst[i + 2] = ((dst[i + 2] as u16 * inv + sb * sa) / 255) as u8;
                dst[i + 3] = 255;
            }
        }
    }
}

