fn draw_text(dst: &mut [u8], dw: u32, dh: u32, x: u32, y: u32, text: &str, scale: u32, rgba: u32) {
    let scale = scale.max(1);
    let r = ((rgba >> 24) & 0xff) as u8;
    let g = ((rgba >> 16) & 0xff) as u8;
    let b = ((rgba >> 8) & 0xff) as u8;
    let mut cx = x;
    for ch in text.chars() {
        if ch == '·' || ch == '•' {
            fill_rect(dst, dw, dh, cx + scale, y + 3 * scale, 2 * scale, 2 * scale, rgba);
            cx += 6 * scale;
            continue;
        }
        let bits = glyph(ch as u8);
        for row in 0..8 {
            let line = bits[row];
            for col in 0..8 {
                if (line >> col) & 1 == 1 {
                    fill_rect(
                        dst,
                        dw,
                        dh,
                        cx + col as u32 * scale,
                        y + row as u32 * scale,
                        scale,
                        scale,
                        (r as u32) << 24 | (g as u32) << 16 | (b as u32) << 8 | 0xff,
                    );
                }
            }
        }
        cx += 8 * scale + scale;
        if cx + 8 * scale >= dw {
            break;
        }
    }
}
